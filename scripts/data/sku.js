/**
 * SKU generation and repair.
 *
 * Shared by the catalogue seeder and the backfill migration so both produce
 * identical values for the same document.
 *
 * Why this exists: MongoDB treats a missing field as `null` when evaluating a
 * unique index, so two documents without a `sku` collide and
 * `createIndex({ sku: 1 }, { unique: true })` fails with
 * `E11000 duplicate key error ... dup key: { sku: null }`. The catalogue
 * predates the `sku` field, so legacy rows must be filled before that index can
 * be built.
 *
 * Generated SKUs are DETERMINISTIC — derived from the document's own `_id` —
 * so re-running the migration produces the same value and is a no-op. That is
 * what makes the migration idempotent.
 */

/** Uppercase alphanumeric token, hyphen-separated, trimmed to `max`. */
function token(value, max) {
  return String(value || '')
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
    .slice(0, max)
    .replace(/-$/, '');
}

/**
 * True when a product row has no usable SKU. Covers all three ways a value can
 * be absent: field missing, explicit null, and empty/whitespace string.
 */
function isMissingSku(product) {
  return (
    product == null ||
    product.sku === undefined ||
    product.sku === null ||
    String(product.sku).trim() === ''
  );
}

/**
 * Builds a stable SKU for a legacy product.
 *
 * Shape: LEG-<PARTCAT>-<NAME>-<ID6>
 *   LEG      marks the row as backfilled rather than generated by the catalogue
 *   PARTCAT  taxonomy slug where known, else the coarse category
 *   NAME     first words of the product name, for human readability
 *   ID6      last 6 hex characters of the ObjectId — the uniqueness guarantee
 *
 * The ObjectId suffix means two products with identical names still get
 * distinct SKUs, and the same product always gets the same SKU.
 */
function legacySkuFor(product) {
  const id = String(product._id || '');
  const idPart = id.slice(-6).toUpperCase() || 'UNKNOWN';
  const catPart = token(product.partCategory || product.category || 'MISC', 6);
  const namePart = token(product.name, 14);

  return ['LEG', catPart, namePart, idPart].filter(Boolean).join('-');
}

/**
 * Assigns SKUs to every product missing one, guaranteeing global uniqueness.
 *
 * @param {Array} products   raw product documents (need `_id`, `name`)
 * @param {Set<string>} taken SKUs already in use; mutated as values are claimed
 * @returns {Array<{_id, sku, previous}>} the assignments to write
 */
function assignMissingSkus(products, taken = new Set()) {
  const assignments = [];

  for (const product of products) {
    if (!isMissingSku(product)) continue;

    let candidate = legacySkuFor(product);

    // The ObjectId suffix makes a collision essentially impossible, but a
    // truncated-name collision is cheap to guard against, so do not rely on it.
    if (taken.has(candidate)) {
      let n = 2;
      while (taken.has(`${candidate}-${n}`)) n++;
      candidate = `${candidate}-${n}`;
    }

    taken.add(candidate);
    assignments.push({ _id: product._id, sku: candidate, previous: product.sku ?? null });
  }

  return assignments;
}

/**
 * Fills every missing SKU in the collection, then verifies the invariant the
 * unique index depends on. Safe to call repeatedly: on a healthy collection it
 * finds nothing to do and returns `{ filled: 0 }`.
 *
 * Also backfills `brand`, which the legacy rows are missing and which the
 * Product schema marks required — without it any later `.save()` on those
 * documents fails validation.
 *
 * @param {import('mongodb').Collection} products
 * @param {object} [opts]
 * @param {boolean} [opts.dryRun=false]  report without writing
 * @param {string}  [opts.fallbackBrand='GearGhar']
 * @param {Function}[opts.log=console.log]
 */
async function ensureProductSkus(products, opts = {}) {
  const { dryRun = false, fallbackBrand = 'GearGhar', log = console.log } = opts;

  const missing = await products
    .find(
      { $or: [{ sku: { $exists: false } }, { sku: null }, { sku: '' }] },
      { projection: { name: 1, brand: 1, category: 1, partCategory: 1 } }
    )
    .toArray();

  const missingBrand = await products.countDocuments({
    $or: [{ brand: { $exists: false } }, { brand: null }, { brand: '' }],
  });

  if (missing.length === 0 && missingBrand === 0) {
    log('✅ SKU check       — every product already has a unique SKU and a brand');
    return { filled: 0, brandsFilled: 0, assignments: [] };
  }

  // Claim the SKUs already in use so generated values cannot collide with them.
  const taken = new Set(
    (await products.distinct('sku', { sku: { $nin: [null, ''] } })).map((s) => String(s))
  );

  const assignments = assignMissingSkus(missing, taken);

  log(`⚠️  SKU backfill    — ${assignments.length} product(s) missing a SKU, ${missingBrand} missing a brand`);
  for (const a of assignments.slice(0, 10)) {
    const source = missing.find((m) => String(m._id) === String(a._id));
    log(`     ${String(a._id)}  "${String(source?.name || '').slice(0, 42)}"  →  ${a.sku}`);
  }
  if (assignments.length > 10) log(`     … +${assignments.length - 10} more`);

  if (dryRun) {
    log('     (dry run — nothing written)');
    return { filled: 0, brandsFilled: 0, assignments };
  }

  let filled = 0;
  if (assignments.length > 0) {
    for (let i = 0; i < assignments.length; i += 400) {
      const ops = assignments.slice(i, i + 400).map((a) => ({
        updateOne: { filter: { _id: a._id }, update: { $set: { sku: a.sku } } },
      }));
      const res = await products.bulkWrite(ops, { ordered: false });
      filled += res.modifiedCount;
    }
  }

  let brandsFilled = 0;
  if (missingBrand > 0) {
    const res = await products.updateMany(
      { $or: [{ brand: { $exists: false } }, { brand: null }, { brand: '' }] },
      { $set: { brand: fallbackBrand } }
    );
    brandsFilled = res.modifiedCount;
  }

  // Verify the invariant rather than assuming the writes landed — this is the
  // precondition the unique index depends on.
  const stillMissing = await products.countDocuments({
    $or: [{ sku: { $exists: false } }, { sku: null }, { sku: '' }],
  });
  if (stillMissing > 0) {
    throw new Error(`SKU backfill incomplete: ${stillMissing} product(s) still have no SKU`);
  }

  log(`✅ SKU backfill    — ${filled} SKU(s) and ${brandsFilled} brand(s) written`);
  return { filled, brandsFilled, assignments };
}

/**
 * Reports duplicate non-null SKUs. A unique index cannot be built while these
 * exist, and unlike missing values they need a human decision, so this only
 * reports.
 */
async function findDuplicateSkus(products) {
  return products
    .aggregate([
      { $match: { sku: { $nin: [null, ''] } } },
      { $group: { _id: '$sku', count: { $sum: 1 }, ids: { $push: '$_id' } } },
      { $match: { count: { $gt: 1 } } },
      { $sort: { count: -1 } },
    ])
    .toArray();
}

/**
 * Creates a unique index safely: fills missing values first, reports genuine
 * duplicates, and turns an E11000 into an actionable message instead of
 * aborting the caller with a bare driver error.
 */
async function createUniqueSkuIndex(products, opts = {}) {
  const { log = console.log } = opts;

  await ensureProductSkus(products, opts);

  const duplicates = await findDuplicateSkus(products);
  if (duplicates.length > 0) {
    log(`❌ Cannot build the unique SKU index — ${duplicates.length} duplicated SKU value(s):`);
    for (const d of duplicates.slice(0, 10)) {
      log(`     "${d._id}" × ${d.count}  (${d.ids.map(String).slice(0, 4).join(', ')})`);
    }
    log('     Resolve these first: npm run normalize:catalog -- --apply');
    return { created: false, reason: 'duplicate_skus', duplicates };
  }

  try {
    await products.createIndex({ sku: 1 }, { unique: true, name: 'sku_1' });
    log('✅ Unique index    — sku_1 created');
    return { created: true };
  } catch (err) {
    if (err && err.code === 11000) {
      log(`❌ sku_1 index failed with E11000 after backfill: ${err.message}`);
      return { created: false, reason: 'e11000', error: err };
    }
    // An existing index with different options reports code 85/86.
    if (err && (err.code === 85 || err.code === 86)) {
      log(`⚠️  sku_1 index already exists with different options — leaving it in place`);
      return { created: false, reason: 'index_conflict' };
    }
    throw err;
  }
}

module.exports = {
  token,
  isMissingSku,
  legacySkuFor,
  assignMissingSkus,
  ensureProductSkus,
  findDuplicateSkus,
  createUniqueSkuIndex,
};
